"""Regenerate examples/sample-digest.md from the synthetic test fixtures.

    python examples/make_sample_digest.py

No network, no API keys, template drafts only. Useful for checking how a
config change (keywords, weights, threshold) moves the synthetic leads.
"""

from __future__ import annotations

import datetime as dt
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from bdrep.config import load_config  # noqa: E402
from bdrep.digest import write_digest  # noqa: E402
from bdrep.drafting import run_drafts  # noqa: E402
from bdrep.pipeline import ingest, score_all  # noqa: E402
from bdrep.sources import FetchResult  # noqa: E402
from bdrep.sources.news_rss import parse_feed  # noqa: E402
from bdrep.sources.sam_gov import parse_search  # noqa: E402
from bdrep.store import Store  # noqa: E402

FIXTURES = ROOT / "tests" / "fixtures"
BANNER = (
    "> **SAMPLE ONLY.** Generated by `examples/make_sample_digest.py` from the synthetic test "
    "fixtures, with template drafts (no API key). Every agency, contact, company and project "
    "below is made up.\n\n"
)


class Static:
    def __init__(self, leads):
        self.leads = leads

    def fetch(self, since, until, prefilter=None):
        return FetchResult(leads=self.leads, requests=3)


def main() -> None:
    cfg = load_config()
    today = dt.date(2026, 10, 10)
    targets = list(cfg.states)
    sources = {
        "sam_gov": Static(parse_search(json.loads((FIXTURES / "sam_search.json").read_text()), targets)),
        "news_rss": Static(parse_feed((FIXTURES / "google_news.xml").read_text(), targets)),
    }
    with tempfile.TemporaryDirectory() as tmp:
        store = Store(Path(tmp) / "leads.db")
        ingest(store, cfg, today, sources=sources)
        score_all(store, cfg)
        run_drafts(store, cfg, use_llm=False)
        digest = write_digest(store, cfg, today, Path(tmp) / "digests")
        out = ROOT / "examples" / "sample-digest.md"
        out.write_text(BANNER + digest.read_text())
        store.close()
    print(out)


if __name__ == "__main__":
    main()
